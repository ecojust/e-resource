import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
globalThis.window = new EventTarget();
globalThis.document = new EventTarget();
document.hidden = false;
let frameId = 0;
window.requestAnimationFrame = () => ++frameId;
window.cancelAnimationFrame = () => {};
const code=readFileSync(new URL('../src/walk-controller.js', import.meta.url),'utf8');
const {WalkController,offsetPosition,distanceMetres}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const canvas=new EventTarget();
canvas.setPointerCapture=()=>{};
let positions=[], cameras=[], notices=[];
const handler=()=>({enabled:true,isEnabled(){return this.enabled},enable(){this.enabled=true},disable(){this.enabled=false}});
const map={getCanvas:()=>canvas, areTilesLoaded:()=>true};
for(const name of ['dragPan','dragRotate','scrollZoom','doubleClickZoom','touchZoomRotate','touchPitch','keyboard','boxZoom'])map[name]=handler();
const scene={map,setPlayer(...args){positions.push(args)},setCameraFromTo(x){cameras.push(x)},collisionAt(){return null},setAvatarVisible(){}};
const ctl=new WalkController(scene,{onNotice:n=>notices.push(n)});
ctl.setEnabled(true);
assert.equal(map.dragPan.enabled,false);
ctl.teleport({lng:121.49,lat:31.24,bearing:0});
const start={...ctl.position};
ctl.keys.add('KeyW');
for(let i=0;i<20;i++)ctl._move(.05,i*50);
assert.ok(Math.abs(distanceMetres(start,ctl.position)-4.2)<.001,'walk speed');
ctl.teleport({...start,bearing:0});ctl.keys.add('KeyW');ctl.keys.add('KeyD');
for(let i=0;i<20;i++)ctl._move(.05,i*50);
assert.ok(Math.abs(distanceMetres(start,ctl.position)-4.2)<.001,'diagonal normalized');
ctl.teleport({...start,bearing:90});ctl.keys.add('KeyW');ctl.setRun(true);
for(let i=0;i<20;i++)ctl._move(.05,i*50);
assert.ok(Math.abs(distanceMetres(start,ctl.position)-8.5)<.001,'running speed');
assert.ok(ctl.position.lng>start.lng && Math.abs(ctl.position.lat-start.lat)<1e-10,'camera-relative east');
ctl.teleport({...start,bearing:0});ctl.keys.add('KeyW');scene.collisionAt=()=> 'water';
ctl._move(.05,6000);
assert.equal(distanceMetres(start,ctl.position),0,'water collision');
scene.collisionAt=(lng,lat)=>lng>start.lng ? 'building':null;
ctl.teleport({...start,bearing:0});ctl.keys.add('KeyW');ctl.keys.add('KeyD');
ctl._move(.05,7000);
assert.equal(ctl.position.lng,start.lng,'wall blocked east movement');
// A footprint wall immediately east of the avatar also blocks its body radius;
// start half a metre away to demonstrate sliding along the facade.
const safe=offsetPosition(start,-.6,0);ctl.teleport({...safe,bearing:0});ctl.keys.add('KeyW');ctl.keys.add('KeyD');
for(let i=0;i<10;i++)ctl._move(.05,8000+i*50);
assert.ok(ctl.position.lat>safe.lat,'sliding preserves north movement');
scene.collisionAt=()=>null;
ctl.setMode('overview');assert.equal(map.dragPan.enabled,true);
ctl.setMode('walk');assert.equal(map.dragPan.enabled,false);
ctl.setMoveVector(9,9);assert.ok(Math.abs(Math.hypot(ctl.moveVector.x,ctl.moveVector.y)-1)<1e-10);
ctl.setLookDelta(0,100000);assert.equal(ctl.pitch,48);
ctl.setLookDelta(0,-100000);assert.equal(ctl.pitch,82);
ctl.resetCamera();assert.equal(ctl.cameraDistance,14);assert.equal(ctl.pitch,82);
ctl._updateCamera(.05,true);assert.ok(cameras.length>0);assert.ok(cameras.at(-1).from.alt>cameras.at(-1).to.alt);
assert.equal(cameras.at(-1).to.alt,3.0,'street architecture framing target');
// A shortened camera must recompose both its aim point and altitude, including
// when the smoothed follow anchor trails a player moving toward the camera.
ctl._follow=offsetPosition(ctl.position,0,.6);scene.collisionAt=()=> 'building';
ctl._updateCamera(.05,true);
assert.equal(cameras.at(-1).to.alt,.90,'close wall lowers target instead of cropping feet');
assert.ok(distanceMetres(ctl.position,cameras.at(-1).to)<.71,'close wall uses the player anchor and shorter look-ahead');
assert.ok(distanceMetres(cameras.at(-1).from,cameras.at(-1).to)<3.5,'camera boom shortens by a wall');
scene.collisionAt=()=>null;
ctl.destroy();assert.equal(map.dragPan.enabled,true);
// Optional street adapter: supported feet and camera move together, while
// removing the local owner restores the original all-city .075 m datum.
let localHeight=.035, revision=1, swept=0;
scene.groundAt=()=>localHeight===null?null:{height:localHeight,id:'paving',ownerId:'bund-streets'};
scene.streetInteractionRevision=()=>revision;
scene.sweepLocalCollision=(from,to,options)=>{
  swept++;assert.equal(options.radius,.38);assert.equal(options.height,1.75);assert.equal(options.maxStepHeight,.2);
  return null;
};
scene.localCameraCollision=()=>null;
const grounded=new WalkController(scene);grounded.setEnabled(true);grounded.teleport({...start,bearing:0});
assert.equal(positions.at(-1)[5],.035,'setPlayer receives actual support height, not a guessed group elevation');
grounded._updateCamera(.05,true);
assert.ok(Math.abs(cameras.at(-1).to.alt-2.96)<1e-12,'camera translates by the same -.04 m authored-ground offset');
const beforeHeightChange=cameras.length;localHeight=.14;revision++;
grounded._tick(1000);
assert.equal(positions.at(-1)[5],.14,'idle avatar reacts to loaded ground height changes');
assert.ok(cameras.length>beforeHeightChange,'height/owner revision invalidates idle camera cache');
assert.ok(Math.abs(cameras.at(-1).to.alt-3.065)<1e-12);
grounded.keys.add('KeyW');grounded._move(.05,1100);assert.ok(swept>0);
const stopped={...grounded.position};
scene.sweepLocalCollision=()=>({blocked:true,type:'street-obstacle',id:'thin-pole'});
grounded._move(.05,1200);assert.equal(distanceMetres(stopped,grounded.position),0,'local swept obstruction stops movement');
const previousRecovery=grounded._spawnTimer;revision++;grounded._syncGround();
assert.notEqual(grounded._spawnTimer,previousRecovery,'late activation around the visitor schedules safe-position recovery');
scene.sweepLocalCollision=()=>null;localHeight=null;revision++;
grounded._sendPlayer(0,0);grounded._updateCamera(.05,true);
assert.equal(positions.at(-1)[5],.075);assert.equal(cameras.at(-1).to.alt,3.0,'unloaded/outside local streets restore prior framing');
grounded.destroy();
console.log('PASS: speed, diagonal normalization, camera-relative movement, water/building collision, sliding, mode gestures, camera limits, and cleanup');
