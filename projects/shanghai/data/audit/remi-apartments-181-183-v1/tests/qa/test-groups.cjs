const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {sourceGroups,assertGroupDraws} = require(process.env.CANDIDATE_AUDIT_GROUPS || '../../../../../tools/candidate-audit-groups.cjs');
const [reviewFile,contractFile,caseFile,reportFile] = process.argv.slice(2);
const read = file => JSON.parse(fs.readFileSync(path.resolve(file)));
const [review,contract,spec,report] = [reviewFile,contractFile,caseFile,reportFile].map(read);
const groups = sourceGroups(review,contract,spec);
assertGroupDraws(groups,report.before.streamedGroups,true);
assertGroupDraws(groups,report.after.streamedGroups,false);
const missing = structuredClone(spec);
missing.groups.pop();
assert.throws(()=>sourceGroups(review,contract,missing),/Coverage/);
const swapped = structuredClone(spec);
[swapped.groups[0].addedOwners,swapped.groups[1].addedOwners] = [swapped.groups[1].addedOwners,swapped.groups[0].addedOwners];
assert.throws(()=>sourceGroups(review,contract,swapped),/Owner missing/);
const repeated = structuredClone(spec);
repeated.groups.push(repeated.groups[0]);
assert.throws(()=>sourceGroups(review,contract,repeated),/Duplicate/);
const badOld = structuredClone(report.before.streamedGroups);
badOld[1].clip_feature_local_ids.push(groups[1].addedOwners[0]);
assert.throws(()=>assertGroupDraws(groups,badOld,true));
const badAfter = structuredClone(report.after.streamedGroups);
badAfter[0].triangles+=2;
assert.throws(()=>assertGroupDraws(groups,badAfter,false));
assert.throws(()=>assertGroupDraws(groups,report.after.streamedGroups.slice(0,1),false),/not drawn/);
console.log('Two positive and six intentional rejection cases passed.');
