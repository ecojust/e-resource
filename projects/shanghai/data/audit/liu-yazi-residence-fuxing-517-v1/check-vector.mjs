import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
const payload=JSON.parse(fs.readFileSync(0));
const runRoot=process.argv[2];
const {planCandidateVectorClipping}=await import(pathToFileURL(path.join(runRoot,'src/candidate-vector-clipping.js')));
const bool=globalThis.polygonClipping;
const {features, originals, srcRule, target, index, m2PerDegree2}=payload;
const parts=g=>g.type==='Polygon'?[g.coordinates]:g.coordinates;
const area=polys=>polys.reduce((a,rings)=>a+rings.reduce((s,ring,i)=>{
  let signed=0;
  for(let j=1;j<ring.length-1;j++) signed+=(ring[j][0]-ring[0][0])*(ring[j+1][1]-ring[0][1])-(ring[j+1][0]-ring[0][0])*(ring[j][1]-ring[0][1]);
  return s+(i?-1:1)*Math.abs(signed)/2;
},0),0)*m2PerDegree2;
const hash=a=>createHash('sha256').update(JSON.stringify(a)).digest('hex');
const solve=(features,source,rules)=>planCandidateVectorClipping(features,{candidateClips:rules},{source,sourceLayer:'building'});
const after=solve(features,'openmaptiles',[srcRule]);assert.equal(after.stats.clippingErrors,0);
assert.deepEqual([...after.desired.values()],[{id:target,residual:true}]);
const original=features.find(f=>f.id===target), chosen=parts(original.geometry)[index],residual=parts(after.residualData.features[0].geometry);
const expected=bool.union(...parts(original.geometry).filter((_,i)=>i!==index));
assert(area(bool.xor(expected,residual))<.0001);
assert(area(bool.intersection(chosen,residual))<.0001);
const before=solve(features,'openmaptiles',[]);assert.equal(before.desired.size,0);
const old=solve(originals,'overture-buildings',[srcRule]);
assert.equal(old.stats.clippingErrors,0);
assert.deepEqual([...old.desired.values()],[{id:srcRule.source_feature_ids.building[0],residual:false}]);
assert.deepEqual(old.residualData.features,[]);
const wrong=solve(originals,'overture-buildings',[{...srcRule,source_feature_ids:{building:['injected-wrong-source-owner'],building_part:[]}}]);assert.equal(wrong.desired.size,0);
const answer={passed:true,source_owner:2849,raw_fallback_area_m2:area([chosen]),public_fallback_group:target,fallback_group_components:parts(original.geometry).length,selected_component:index,other_component_union_xor_m2:area(bool.xor(expected,residual)),selected_source_overlap_after_m2:area(bool.intersection(chosen,residual)),actual_remaining_fallback_hash:hash(residual),stats:after.stats,overture_removed:[...old.desired.values()],overture_kept:originals.filter(g=>g.id!==srcRule.source_feature_ids.building[0]).map(g=>g.id),unregistered_state_unmodified:true,wrong_source_owner_rejected:true};
process.stdout.write(JSON.stringify(answer));
