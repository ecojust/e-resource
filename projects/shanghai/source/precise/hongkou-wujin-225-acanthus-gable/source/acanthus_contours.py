# Metric mapping from the free quadrilateral of the drawing to the orthogonal
# reference plane determined from the gable photograph. Both grids use 720 × 370.
DRAWING_TO_METRIC = ((0.959555717003, 0.165855860458, -29.75458225765), (0.008032485406, 1.029639456422, -3.67538833444), (-9.824811e-05, 0.000168722943, 1.0))

def metric_point(u,v):
    a,b,c=DRAWING_TO_METRIC
    denominator=c[0]*u+c[1]*v+c[2]
    return ((a[0]*u+a[1]*v+a[2])/denominator,
            (b[0]*u+b[1]*v+b[2])/denominator)
